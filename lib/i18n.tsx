'use client'

import {
  createContext,
  useContext,
  useEffect,
  useState,
  type ReactNode,
} from 'react'

export type AppLang = 'en' | 'bn'

const LANG_KEY = 'tokio-lang'

interface LangCtx {
  lang: AppLang
  setLang: (lang: AppLang) => void
  t: (key: string) => string
}

const Ctx = createContext<LangCtx>({ lang: 'en', setLang: () => {}, t: (k) => k })

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<AppLang>('en')

  useEffect(() => {
    try {
      const saved = window.localStorage.getItem(LANG_KEY)
      if (saved === 'en' || saved === 'bn') setLangState(saved)
    } catch {}
  }, [])

  useEffect(() => {
    document.documentElement.lang = lang === 'bn' ? 'bn' : 'en'
  }, [lang])

  const setLang = (next: AppLang) => {
    setLangState(next)
    try {
      window.localStorage.setItem(LANG_KEY, next)
    } catch {}
  }

  const t = (key: string) => STRINGS[lang][key] ?? STRINGS.en[key] ?? key

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>
}

export function useLang() {
  return useContext(Ctx)
}

export function getStoredLang(): AppLang | null {
  try {
    const v = window.localStorage.getItem(LANG_KEY)
    return v === 'en' || v === 'bn' ? v : null
  } catch {
    return null
  }
}

